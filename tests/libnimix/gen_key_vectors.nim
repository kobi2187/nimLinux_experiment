## Regenerates tests/libnimix/key_vectors.txt from input/evdev_keymap.nim (the
## authority for evdev -> character). libnimix/nimix_keymap.h (C, used by the raylib
## platform) must reproduce every line, so the two keymaps cannot drift apart.
## Run: nim c -r tests/libnimix/gen_key_vectors.nim > tests/libnimix/key_vectors.txt
import ../../input/evdev_keymap

echo "# code flags char   flags: bit0 shift, bit1 caps lock on, bit2 ctrl; char -1 = none"
echo "# (generated by gen_key_vectors.nim from input/evdev_keymap.nim; do not edit)"
for flags in 0 .. 7:
  for code in 0 .. 127:
    var ks: KeyState
    if (flags and 1) != 0: discard ks.keyToChar(42, 1)       # left shift down
    if (flags and 2) != 0: discard ks.keyToChar(58, 1)       # caps lock pressed: on
    if (flags and 4) != 0: discard ks.keyToChar(29, 1)       # left ctrl down
    echo code, " ", flags, " ", ks.keyToChar(uint16(code), 1)

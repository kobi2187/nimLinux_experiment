## Regenerates tests/libnimix/clock_vectors.txt from core/tsc_clock.nim (the
## authority). Both the Nim test and the C test (libnimix/nimix_timepage.h)
## must reproduce every line, so the two implementations cannot drift apart.
## Run: nim c -r tests/libnimix/gen_clock_vectors.nim > tests/libnimix/clock_vectors.txt
import ../../core/tsc_clock

const
  Freqs: array[7, uint64] = [1_000_000'u64, 1_000_000_001'u64, 1_800_000_000'u64, 2_300_000_000'u64,
                             2_994_321_772'u64, 4_700_000_000'u64, 100_000_000_000'u64]
  Deltas: array[9, uint64] = [0'u64, 1'u64, 4_294_967_295'u64, 4_294_967_296'u64, 1_000_000_007'u64,
                              123_456_789_012'u64, 9_999_999_999_999'u64, 281_474_976_710_655'u64,
                              4_611_686_018_427_387'u64]
echo "# hz base mul shift tsc nanos   (generated by gen_clock_vectors.nim; do not edit)"
for hz in Freqs:
  let c = newTscClock(0x1234_5678_9ABC'u64, hz)
  for d in Deltas:
    let tsc = c.base + d
    echo hz, " ", c.base, " ", c.mul, " ", c.shift, " ", tsc, " ", clockNanos(c, tsc)

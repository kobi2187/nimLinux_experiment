## App entry contract. The kernel enters an app at `appMain` (built --noMain),
## so Nim's module initialisation never ran on its own: every global with a
## runtime initialiser stayed zero — notably the heap's bump pointer, so the
## first allocation returned address 0 (#PF at CR2=0x18 in dispatch_server).
## Call nimixAppInit() as the first statement of appMain.

proc NimMain() {.importc, cdecl.}   ## generated by Nim even with --noMain

template nimixAppInit*() =
  ## Run all module initialisers (system heap, cps, msgpack, app globals).
  NimMain()

"""bdf2nim — turn a fixed-cell BDF bitmap font into a Nim module for gfx/.

    tools/bdf2nim.py vendor/fonts/spleen-8x16.bdf spleen8x16 > gfx/font_spleen8x16.nim

Keeps ASCII, Latin-1 and box drawing / block elements (what a terminal needs).
Every glyph must fill the font's bounding box (true for terminal fonts).
Output: a sorted codepoint table + (width+7)/8 bytes per row, MSB = leftmost.
"""
import sys

RANGES = [(0x20, 0x7E), (0xA0, 0xFF), (0x2500, 0x259F)]


def wanted(cp: int) -> bool:
    return any(lo <= cp <= hi for lo, hi in RANGES)


def parse(path):
    width = height = None
    glyphs = {}
    cp, rows, in_bitmap = None, [], False
    for line in open(path, encoding="latin-1"):
        f = line.split()
        if not f:
            continue
        if f[0] == "FONTBOUNDINGBOX":
            width, height = int(f[1]), int(f[2])
        elif f[0] == "ENCODING":
            cp = int(f[1])
        elif f[0] == "BBX":
            assert (int(f[1]), int(f[2])) == (width, height), f"U+{cp:04X}: not a full-cell glyph"
        elif f[0] == "BITMAP":
            in_bitmap, rows = True, []
        elif f[0] == "ENDCHAR":
            in_bitmap = False
            if cp is not None and cp >= 0 and wanted(cp):
                glyphs[cp] = rows
        elif in_bitmap:
            rows.append(int(f[0], 16))
    return width, height, glyphs


def main():
    path, name = sys.argv[1], sys.argv[2]
    width, height, glyphs = parse(path)
    row_bytes = (width + 7) // 8
    cps = sorted(glyphs)
    out = [f"# SPDX-License-Identifier: BSD-2-Clause",
           f"# GENERATED by tools/bdf2nim.py from {path} — do not edit.",
           f"# Font licence: vendor/fonts/LICENSE.spleen (BSD-2-Clause).",
           f"## {name}: {width}x{height} bitmap font, {len(cps)} glyphs "
           f"(ASCII, Latin-1, box drawing).",
           "",
           "import bitmap_font",
           "",
           f"let {name}Codepoints = [",
           ]
    for i in range(0, len(cps), 10):
        out.append("  " + ", ".join(f"0x{c:04X}'u32" for c in cps[i:i + 10]) + ",")
    out += ["]", "", f"let {name}Rows = ["]
    for cp in cps:
        bs = []
        for r in glyphs[cp]:
            bs += [(r >> (8 * (row_bytes - 1 - k))) & 0xFF for k in range(row_bytes)]
        assert len(bs) == height * row_bytes, f"U+{cp:04X}: wrong row count"
        out.append("  " + ", ".join(f"0x{b:02X}'u8" for b in bs) + f",  # U+{cp:04X}")
    out += ["]", "",
            f"let {name}* = BitmapFont(width: {width}, height: {height}, "
            f"count: {len(cps)},",
            f"  codepoints: cast[ptr UncheckedArray[uint32]](unsafeAddr {name}Codepoints[0]),",
            f"  rows: cast[ptr UncheckedArray[uint8]](unsafeAddr {name}Rows[0]))",
            ""]
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()

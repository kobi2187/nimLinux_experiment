#!/usr/bin/env python3
# SPDX-License-Identifier: GPL-2.0
"""Adapt naylib (vendor/naylib, pinned) to the raylib bridge's C side.

naylib v25.51.1 binds raylib 5.6-dev and hard-wires its own GLFW build. We keep
its Nim API (names, types, RAII destructors RUI relies on) and:
  1. replace the build header with raylib 6.2 from vendor/raylib, memory
     platform + rlsw (no GLFW, no utils.c, no raudio);
  2. empty naylib's config.nim (5.x -D flags) so 6.2's own config.h applies;
  3. correct the declarations whose C ABI changed in 6.2.
Output: build/bridge/naylib/{raylib,rlgl,raymath,...}.nim (generated; do not edit).
Usage: tools/naylib_adapt.py [repo_root]
"""
import pathlib, re, shutil, sys

root = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else ".").resolve()
src = root / "vendor/naylib/src"
out = root / "build/bridge/naylib"

BUILD = '''const raylibDir = Path"%s"
{.passC: "-I" & raylibDir.string.}
{.passC: "-D_GNU_SOURCE -Wno-missing-braces".}
{.passC: "-DPLATFORM_MEMORY -DGRAPHICS_API_OPENGL_SOFTWARE -DSUPPORT_MODULE_RAUDIO=0".}
# RUI caches one render target per widget: rlsw's defaults (8 FBOs, 128
# textures) are far too few. Heap pools, so the cost is a handle table.
{.passC: "-DRLSW_MAX_FRAMEBUFFERS=512 -DRLSW_MAX_TEXTURES=2048".}
{.compile: raylibDir / Path"rcore.c".}
{.compile: raylibDir / Path"rshapes.c".}
{.compile: raylibDir / Path"rtextures.c".}
{.compile: raylibDir / Path"rtext.c".}
{.compile: raylibDir / Path"rmodels.c".}
{.passL: "-lm".}
''' % (root / "vendor/raylib/src").as_posix()

# (old declaration regex, new declaration) — raylib 6.2 signatures.
ABI = [
    # naylib's bundled raylib.h renames Rectangle (a Win32 clash); upstream 6.2 does not.
    (r'Rectangle\* \{\.importc: "rlRectangle"', 'Rectangle* {.importc: "Rectangle"'),
    (r'proc drawCircleGradient\*\(centerX: int32, centerY: int32, radius',
     'proc drawCircleGradient*(center: Vector2, radius'),
    (r'func imageColorContrast\*\(image: var Image, contrast: float32\)',
     'func imageColorContrast*(image: var Image, contrast: int32)'),
    (r'func imageDrawRectangleLines\*\(dst: var Image, rec: Rectangle, thick: int32, color: Color\) \{\.importc: "ImageDrawRectangleLines"\.\}',
     'func imageDrawRectangleLines*(dst: var Image, rec: Rectangle, thick: int32, color: Color) {.importc: "ImageDrawRectangleLinesEx".}'),
    (r'proc updateModelAnimation\*\(model: Model, anim: ModelAnimation, frame: int32\)',
     'proc updateModelAnimation*(model: Model, anim: ModelAnimation, frame: float32)'),
    (r'proc drawCapsule\*\(startPos: Vector3, endPos: Vector3, radius: float32, slices: int32, rings: int32',
     'proc drawCapsule*(startPos: Vector3, endPos: Vector3, radius: float32, rings: int32, slices: int32'),
    (r'proc drawCapsuleWires\*\(startPos: Vector3, endPos: Vector3, radius: float32, slices: int32, rings: int32',
     'proc drawCapsuleWires*(startPos: Vector3, endPos: Vector3, radius: float32, rings: int32, slices: int32'),
]

# naylib renames these C symbols (rlCloseWindow...) to dodge Win32 clashes in its
# bundled raylib; upstream 6.2 exports the plain names.
RENAMED = ["CloseWindow", "ShowCursor", "LoadImage", "DrawText", "DrawTextEx"]

def adapt_raylib(text):
    start = text.index('const raylibDir')
    end = text.index('\nconst\n  RaylibVersion')
    text = text[:start] + BUILD + text[end:]
    for old, new in ABI:
        text, n = re.subn(old, new, text)
        if n != 1:
            sys.exit(f"naylib_adapt: ABI patch matched {n} times: {old}")
    for name in RENAMED:
        text, n = re.subn(r'importc: "rl%s"' % name, 'importc: "%s"' % name, text)
        if n != 1:
            sys.exit(f"naylib_adapt: rename {name} matched {n} times")
    return "# GENERATED by tools/naylib_adapt.py from vendor/naylib — do not edit.\n" + text

def main():
    if out.exists():
        shutil.rmtree(out)
    shutil.copytree(src, out, ignore=shutil.ignore_patterns("raylib"))  # skip naylib's bundled C
    rl = out / "raylib.nim"
    rl.write_text(adapt_raylib(rl.read_text()))
    cfg = out / "naylib/private/config.nim"
    # config.nim only emits -D flags mirroring 5.x's config.h; 6.2's own config.h applies.
    cfg.write_text("# GENERATED: naylib's config flags dropped; raylib 6.2 config.h applies.\n")
    print(f"naylib_adapt: wrote {out.relative_to(root)}")

main()

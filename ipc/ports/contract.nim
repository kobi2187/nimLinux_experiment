## The port contract (K1, human 2026-11-18: option 1, "keep simple machinery"): the Nim wire types in
## ipc/ports/*.nim ARE the contract. This module turns them into the C side, so the two cannot drift:
##   * `generateHeader`  the text of libnimix/nimix_contract.h: constants, enums, and packed structs with a
##                       size check, all read from the Nim types by the compiler (`fieldPairs`, `sizeof`, `ord`);
##   * `generateVectors` sample messages built by the REAL Nim encoders, as hex, for the C host tests.
## There is no description language here and none is meant to grow: a field type with no C mapping is a
## compile error, and adding a message means adding it to the two lists at the bottom.
## Pure: no files, no hardware. tools/gen_contract.nim writes the files; tests/test_contract.nim checks them.
import std/[strutils, typetraits]
import port, input_port, display_port
import ../handles/channel

# ── C type names ──────────────────────────────────────────────────────────────

proc cName(T: typedesc): string =
  when T is uint8 or T is bool: "uint8_t"
  elif T is uint16: "uint16_t"
  elif T is int16: "int16_t"
  elif T is uint32: "uint32_t"
  elif T is int32: "int32_t"
  elif T is uint64: "uint64_t"
  elif T is int64: "int64_t"
  elif T is object: "Nimix" & name(T)
  else: {.error: "a wire field has a type with no C mapping".}

proc cStruct(T: typedesc[object]): string =
  ## A packed C struct with the same fields in the same order, and a size check against Nim's own `sizeof`.
  var tmp: T
  result = "typedef struct __attribute__((packed)) {\n"
  for fname, fval in fieldPairs(tmp):
    when fval is array:
      result.add "    " & cName(typeof(fval[0])) & " " & fname & "[" & $fval.len & "];\n"
    else:
      result.add "    " & cName(typeof(fval)) & " " & fname & ";\n"
  let cn = cName(T)
  result.add "} " & cn & ";\n"
  result.add "_Static_assert(sizeof(" & cn & ") == " & $sizeof(T) & ", \"" & cn & " must match its Nim type\");\n\n"

proc cEnum(E: typedesc[enum]): string =
  result = "enum {  /* " & name(E) & " */\n"
  for e in E: result.add "    NIMIX_" & name(E) & "_" & $e & " = " & $ord(e) & ",\n"
  result.add "};\n\n"

# ── the header ────────────────────────────────────────────────────────────────

proc generateHeader*(): string =
  result = """/* SPDX-License-Identifier: GPL-2.0
 * GENERATED by tools/gen_contract.nim from the Nim files in ipc/ports/. DO NOT EDIT.
 * Regenerate with `make gen-contract`; tests/test_contract.nim fails if this file is stale.
 *
 * The device-port wire contract for C programs: constants, enum values and packed structs, read straight from
 * the Nim types. Fields are little endian and the structs are packed, so a C program reads a payload by copying
 * it into the struct (x86 only, like the rest of NimixOS). */
#pragma once
#include <stdint.h>

#if !defined(__BYTE_ORDER__) || __BYTE_ORDER__ != __ORDER_LITTLE_ENDIAN__
#error "the port wire contract is little endian"
#endif

"""
  result.add "#define NIMIX_PORT_HEADER " & $PortHeaderBytes & "\n"
  result.add "#define NIMIX_CONTRACT_MSG_BYTES " & $ChMsgBytes & "\n"
  result.add "#define NIMIX_PORT_DESCRIBE_OP 0x" & toHex(int(PortDescribeOp), 4) & "u\n"
  result.add "#define NIMIX_PORT_LOST_OP 0x" & toHex(int(EventLostOp), 4) & "u\n"
  result.add "#define NIMIX_DISPLAY_MAX_MODES " & $MaxWireModes & "\n"
  result.add "#define NIMIX_DISPLAY_FORMAT_B8G8R8X8 " & $FormatBgrx & "\n\n"
  result.add cEnum(MsgClass)
  result.add cEnum(PortStatus)
  result.add cEnum(PortKind)
  result.add cEnum(InputOp)
  result.add cEnum(InputKind)
  result.add cEnum(KeyAction)
  result.add cEnum(DisplayOp)
  result.add cStruct(LostWire)
  result.add cStruct(InputInfo)
  result.add cStruct(KeyWire)
  result.add cStruct(MotionWire)
  result.add cStruct(ButtonWire)
  result.add cStruct(WheelWire)
  result.add cStruct(ModeWire)
  result.add cStruct(DisplayInfoWire)
  result.add cStruct(DisplayModesWire)
  result.add cStruct(SetModeWire)
  result.add cStruct(PresentWire)

# ── test vectors ──────────────────────────────────────────────────────────────

proc hexOf(m: PortMsg): string =
  var buf: array[ChMsgBytes, byte]
  let n = toWire(m, buf)
  for i in 0 ..< n: result.add toHex(int(buf[i]), 2).toLowerAscii

proc ev(e: InputEvent): string =
  var m: PortMsg
  encode(e, m)
  hexOf(m)


proc generateVectors*(): string =
  ## One line per message: `<kind> <field values...> = <hex of the whole wire message>`. The hex comes from the real
  ## Nim encoders; the C tests decode events from it and check that the C library builds the same request bytes.
  result = "# GENERATED by tools/gen_contract.nim. DO NOT EDIT. Regenerate with `make gen-contract`.\n"
  result.add "# event lines: the C decoder must read these fields out of these bytes\n"
  result.add "event key 30 1 0 0 = " & ev(InputEvent(kind: ikKey, code: 30, action: kaDown)) & "\n"
  result.add "event key 30 2 0 0 = " & ev(InputEvent(kind: ikKey, code: 30, action: kaRepeat)) & "\n"
  result.add "event key 65535 0 0 0 = " & ev(InputEvent(kind: ikKey, code: 65535, action: kaUp)) & "\n"
  result.add "event motion -5 300 0 0 = " & ev(InputEvent(kind: ikMotion, dx: -5, dy: 300, absolute: false)) & "\n"
  result.add "event motion 32767 16384 1 0 = " & ev(InputEvent(kind: ikMotion, dx: 32767, dy: 16384, absolute: true)) & "\n"
  result.add "event button 272 1 0 0 = " & ev(InputEvent(kind: ikButton, button: 272, pressed: true)) & "\n"
  result.add "event wheel -1 3 0 0 = " & ev(InputEvent(kind: ikWheel, wheelX: -1, wheelY: 3)) & "\n"
  result.add "event lost 12345 0 0 0 = " & ev(InputEvent(kind: ikLost, lost: 12345)) & "\n"
  result.add "# request lines: the C library must send exactly these bytes\n"
  var m: PortMsg
  m = displayRequest(doInfo)
  result.add "request info = " & hexOf(m) & "\n"
  m = displayRequest(doModes)
  result.add "request modes = " & hexOf(m) & "\n"
  m = displayRequest(doSetMode); putPayload(m, SetModeWire(w: 800, h: 600))
  result.add "request setmode 800 600 = " & hexOf(m) & "\n"
  m = displayRequest(doPresent)
  putPayload(m, PresentWire(handle: 7, strideBytes: 2560, sx: 1, sy: 2, w: 640, h: 400, dx: -10, dy: 20))
  result.add "request present 7 2560 1 2 640 400 -10 20 = " & hexOf(m) & "\n"
